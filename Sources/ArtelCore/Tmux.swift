import Foundation

/// Artel's private tmux server (`tmux -L artel`). Sessions live here so they survive app restarts.
public struct Tmux: Sendable {
    public static let defaultSocketName = "artel"
    /// Session names are `artel-<record id>`.
    public static let sessionPrefix = "artel-"

    public let executable: String
    public let configFile: URL
    public let environment: [String: String]
    /// `-L` name: `artel`, or `aide` while sessions started by Aide still run there (see `LegacyAide`).
    public let socketName: String

    public init(executable: String, configFile: URL = AppPaths.tmuxConf, environment: [String: String],
                socketName: String = Tmux.defaultSocketName) {
        self.executable = executable
        self.configFile = configFile
        self.environment = environment
        self.socketName = socketName
    }

    /// Base arguments: private socket and our config (applied when the server starts).
    var baseArgs: [String] { ["-L", socketName, "-f", configFile.path] }

    @discardableResult
    func tmux(_ args: [String]) throws -> ProcessResult {
        try Shell.run(executable, baseArgs + args, environment: environment, timeout: 10)
    }

    public func version() -> String? {
        guard let r = try? Shell.run(executable, ["-V"], timeout: 5), r.ok else { return nil }
        return r.stdout.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    public func listSessions() -> Set<String> {
        guard let r = try? tmux(["list-sessions", "-F", "#{session_name}"]), r.ok else { return [] }
        return Set(r.stdout.split(whereSeparator: \.isNewline).map(String.init))
    }

    public func hasSession(_ name: String) -> Bool {
        (try? tmux(["has-session", "-t", "=\(name)"]))?.ok ?? false
    }

    public static func newSessionArgs(name: String, cwd: String, env: [String: String], command: [String]) -> [String] {
        var args = ["new-session", "-d", "-s", name, "-c", cwd, "-x", "200", "-y", "50"]
        for (k, v) in env.sorted(by: { $0.key < $1.key }) { args += ["-e", "\(k)=\(v)"] }
        // argv form: tmux execs the command directly, no shell quoting involved.
        return args + ["--"] + command
    }

    public func newSession(name: String, cwd: String, env: [String: String], command: [String]) throws {
        let r = try tmux(Self.newSessionArgs(name: name, cwd: cwd, env: env, command: command))
        guard r.ok else { throw ArtelError.tmux(r.stderr.trimmingCharacters(in: .whitespacesAndNewlines)) }
    }

    /// Pastes text as one bracketed paste (multi-line prompts stay one message), optionally pressing Enter.
    public func paste(_ text: String, into name: String, submit: Bool) throws {
        let file = FileManager.default.temporaryDirectory.appendingPathComponent("artel-paste-\(UUID().uuidString)")
        try text.write(to: file, atomically: true, encoding: .utf8)
        defer { try? FileManager.default.removeItem(at: file) }
        let buffer = "artel-\(UUID().uuidString.prefix(8))"
        var r = try tmux(["load-buffer", "-b", buffer, file.path])
        guard r.ok else { throw ArtelError.tmux(r.stderr) }
        r = try tmux(["paste-buffer", "-p", "-d", "-b", buffer, "-t", "=\(name):"])
        guard r.ok else { throw ArtelError.tmux(r.stderr) }
        if submit {
            usleep(300_000)  // let the TUI finish handling the paste before Enter
            try sendKeys(["Enter"], to: name)
        }
    }

    /// Types a short command line (e.g. `/clear`) and presses Enter.
    public func sendLine(_ line: String, to name: String) throws {
        let r = try tmux(["send-keys", "-t", "=\(name):", "-l", line])
        guard r.ok else { throw ArtelError.tmux(r.stderr) }
        usleep(150_000)
        try sendKeys(["Enter"], to: name)
    }

    public func sendKeys(_ keys: [String], to name: String) throws {
        let r = try tmux(["send-keys", "-t", "=\(name):"] + keys)
        guard r.ok else { throw ArtelError.tmux(r.stderr) }
    }

    public func kill(_ name: String) {
        _ = try? tmux(["kill-session", "-t", "=\(name)"])
    }

    public func rename(_ name: String, to newName: String) {
        _ = try? tmux(["rename-session", "-t", "=\(name)", newName])
    }

    /// Arguments for a client that shows the session in a terminal view.
    public func attachArgs(_ name: String) -> [String] {
        baseArgs + ["attach-session", "-t", "=\(name)"]
    }

    /// Our tmux config: invisible chrome, mouse scrolling, no key delay, true colour.
    public static let config = """
    # Generated by Artel; overwritten on launch.
    set -g status off
    set -g mouse on
    set -g escape-time 0
    set -g history-limit 50000
    set -g focus-events on
    set -g extended-keys on
    set -g extended-keys-format csi-u
    set -g allow-passthrough on
    set -g set-clipboard on
    set -g default-terminal "tmux-256color"
    set -as terminal-features ",xterm-256color:RGB:extkeys"
    set -g window-size latest
    set -g aggressive-resize on
    set -g destroy-unattached off
    set -g exit-empty off
    """

    public static func writeConfig(to url: URL = AppPaths.tmuxConf) throws {
        try config.write(to: url, atomically: true, encoding: .utf8)
    }
}

public enum ArtelError: LocalizedError, Equatable {
    case tmux(String)
    case toolMissing(String)
    case invalidProject(String)
    case git(String)

    public var errorDescription: String? {
        switch self {
        case .tmux(let msg): "tmux: \(msg)"
        case .toolMissing(let tool): "\(tool) not found"
        case .invalidProject(let msg): msg
        case .git(let msg): "git: \(msg)"
        }
    }
}
